-- =============================================================================
-- Supply Chain Inventory Optimization & Reorder Forecasting
-- PostgreSQL schema (v1.0)
--
-- Design notes
--   * Supplier lead time is stored at supplier level (the operational driver),
--     while each purchase order snapshots its quoted lead time at order time.
--   * Current stock is not denormalized onto products. The latest row in
--     inventory_snapshots is the source of truth for on-hand inventory.
--   * Analytics outputs are generated in Python and exported to Tableau; SQL
--     views in 02_views.sql expose the same core logic for a live database.
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS supply_chain;
SET search_path TO supply_chain, public;

CREATE TABLE IF NOT EXISTS suppliers (
    supplier_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name           TEXT        NOT NULL UNIQUE,
    country_code            CHAR(2)     NOT NULL,
    promised_lead_time_days SMALLINT    NOT NULL CHECK (promised_lead_time_days BETWEEN 1 AND 365),
    lead_time_sigma_days    NUMERIC(6, 2) NOT NULL CHECK (lead_time_sigma_days >= 0),
    on_time_target_pct      NUMERIC(5, 4) NOT NULL CHECK (on_time_target_pct > 0 AND on_time_target_pct <= 1),
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE suppliers IS
    'Approved suppliers with contractual lead time and historical variability assumptions.';
COMMENT ON COLUMN suppliers.promised_lead_time_days IS
    'Quoted/contractual calendar-day lead time used for planning and ROP.';
COMMENT ON COLUMN suppliers.lead_time_sigma_days IS
    'Planning assumption for the standard deviation of actual lead time (days).';

CREATE TABLE IF NOT EXISTS products (
    product_id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku                 VARCHAR(32)  NOT NULL UNIQUE,
    product_name        TEXT         NOT NULL,
    category            VARCHAR(64)  NOT NULL,
    demand_pattern      VARCHAR(16)  NOT NULL
                        CHECK (demand_pattern IN ('steady', 'seasonal', 'intermittent')),
    supplier_id         INTEGER      NOT NULL REFERENCES suppliers (supplier_id),
    unit_cost           NUMERIC(12, 2) NOT NULL CHECK (unit_cost > 0),
    unit_price          NUMERIC(12, 2) NOT NULL CHECK (unit_price >= unit_cost),
    holding_cost_pct    NUMERIC(5, 4) NOT NULL CHECK (holding_cost_pct > 0 AND holding_cost_pct <= 1),
    ordering_cost       NUMERIC(12, 2) NOT NULL CHECK (ordering_cost > 0),
    min_order_qty       INTEGER      NOT NULL DEFAULT 1 CHECK (min_order_qty > 0),
    target_service_level NUMERIC(4, 3) NOT NULL DEFAULT 0.950
                        CHECK (target_service_level > 0 AND target_service_level < 1),
    is_active           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON COLUMN products.holding_cost_pct IS
    'Annual inventory carrying rate applied to unit cost, e.g. 0.22 = 22% per year.';
COMMENT ON COLUMN products.ordering_cost IS
    'Fixed cost per replenishment order (S in the EOQ model).';
COMMENT ON COLUMN products.target_service_level IS
    'Desired cycle service level used to choose Z in the safety-stock calculation.';

CREATE TABLE IF NOT EXISTS sales_transactions (
    sale_id       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT       NOT NULL REFERENCES products (product_id),
    sale_date     DATE         NOT NULL,
    quantity_sold INTEGER      NOT NULL CHECK (quantity_sold > 0),
    unit_price    NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    channel       VARCHAR(24)  NOT NULL
                  CHECK (channel IN ('Retail', 'Wholesale', 'Online')),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_sales_product_date
    ON sales_transactions (product_id, sale_date);
CREATE INDEX IF NOT EXISTS ix_sales_date
    ON sales_transactions (sale_date);

COMMENT ON TABLE sales_transactions IS
    'Line-level fulfilled demand. Lost sales from stockouts are not recorded here; '
    'inventory snapshots provide the operational stock context.';

CREATE TABLE IF NOT EXISTS purchase_orders (
    po_id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_number             VARCHAR(32)  NOT NULL UNIQUE,
    product_id            BIGINT       NOT NULL REFERENCES products (product_id),
    supplier_id           INTEGER      NOT NULL REFERENCES suppliers (supplier_id),
    order_date            DATE         NOT NULL,
    promised_date         DATE         NOT NULL,
    received_date         DATE,
    quantity_ordered      INTEGER      NOT NULL CHECK (quantity_ordered > 0),
    quantity_received     INTEGER      NOT NULL DEFAULT 0 CHECK (quantity_received >= 0),
    unit_cost             NUMERIC(12, 2) NOT NULL CHECK (unit_cost > 0),
    status                VARCHAR(24)  NOT NULL
                          CHECK (status IN ('OPEN', 'PARTIALLY_RECEIVED', 'RECEIVED', 'CANCELLED')),
    quoted_lead_time_days SMALLINT     NOT NULL CHECK (quoted_lead_time_days BETWEEN 1 AND 365),
    notes                 TEXT,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_po_promised_after_order CHECK (promised_date >= order_date),
    CONSTRAINT ck_po_received_after_order CHECK (received_date IS NULL OR received_date >= order_date),
    CONSTRAINT ck_po_received_qty CHECK (quantity_received <= quantity_ordered),
    CONSTRAINT ck_po_received_status CHECK (
        status <> 'RECEIVED' OR received_date IS NOT NULL
    )
);

CREATE INDEX IF NOT EXISTS ix_po_product_order
    ON purchase_orders (product_id, order_date);
CREATE INDEX IF NOT EXISTS ix_po_supplier_order
    ON purchase_orders (supplier_id, order_date);
CREATE INDEX IF NOT EXISTS ix_po_open
    ON purchase_orders (status, promised_date)
    WHERE status IN ('OPEN', 'PARTIALLY_RECEIVED');

COMMENT ON COLUMN purchase_orders.quoted_lead_time_days IS
    'Lead time quoted on this specific PO; protects analysis from later contract changes.';
COMMENT ON COLUMN purchase_orders.promised_date IS
    'Promised arrival date = order_date + quoted_lead_time_days.';
COMMENT ON COLUMN purchase_orders.received_date IS
    'Actual warehouse receipt date; NULL while the order is open.';

CREATE TABLE IF NOT EXISTS inventory_snapshots (
    snapshot_date  DATE   NOT NULL,
    product_id     BIGINT NOT NULL REFERENCES products (product_id),
    on_hand_units  INTEGER NOT NULL CHECK (on_hand_units >= 0),
    inbound_units  INTEGER NOT NULL DEFAULT 0 CHECK (inbound_units >= 0),
    PRIMARY KEY (snapshot_date, product_id)
);

CREATE INDEX IF NOT EXISTS ix_inventory_latest
    ON inventory_snapshots (product_id, snapshot_date DESC);

COMMENT ON TABLE inventory_snapshots IS
    'Weekly and horizon-end on-hand positions. inbound_units are open POs at snapshot time.';

